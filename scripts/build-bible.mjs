// Builds data/bible.json (verse text) and lib/bible/books.generated.ts (book names + verse counts)
// from the public-domain source files in data/raw/. Run with: npm run build:bible
//   KJV.json, BSB.json  scrollmapper/bible_databases
//   LSG.xml             Beblia/Holy-Bible-XML-Format (Louis Segond 1910)
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const TRANSLATIONS = ["KJV", "BSB", "LSG"];

const FRENCH_NAMES = [
  "Genèse", "Exode", "Lévitique", "Nombres", "Deutéronome", "Josué", "Juges", "Ruth", "1 Samuel", "2 Samuel",
  "1 Rois", "2 Rois", "1 Chroniques", "2 Chroniques", "Esdras", "Néhémie", "Esther", "Job", "Psaumes", "Proverbes",
  "Ecclésiaste", "Cantique des cantiques", "Ésaïe", "Jérémie", "Lamentations", "Ézéchiel", "Daniel", "Osée", "Joël",
  "Amos", "Abdias", "Jonas", "Michée", "Nahum", "Habacuc", "Sophonie", "Aggée", "Zacharie", "Malachie",
  "Matthieu", "Marc", "Luc", "Jean", "Actes", "Romains", "1 Corinthiens", "2 Corinthiens", "Galates", "Éphésiens",
  "Philippiens", "Colossiens", "1 Thessaloniciens", "2 Thessaloniciens", "1 Timothée", "2 Timothée", "Tite",
  "Philémon", "Hébreux", "Jacques", "1 Pierre", "2 Pierre", "1 Jean", "2 Jean", "3 Jean", "Jude", "Apocalypse",
];

const loadJson = (t) => JSON.parse(fs.readFileSync(path.join(root, "data/raw", `${t}.json`), "utf8"));

const decode = (s) =>
  s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;|&#39;/g, "'");

// The Beblia XML is a flat <book><chapter><verse> tree; a small regex reader is enough.
function loadXml(t) {
  const xml = fs.readFileSync(path.join(root, "data/raw", `${t}.xml`), "utf8");
  const books = [];
  for (const b of xml.matchAll(/<book number="(\d+)">([\s\S]*?)<\/book>/g)) {
    const chapters = [];
    for (const c of b[2].matchAll(/<chapter number="(\d+)">([\s\S]*?)<\/chapter>/g)) {
      const verses = [...c[2].matchAll(/<verse number="(\d+)">([\s\S]*?)<\/verse>/g)].map((v) => ({
        verse: Number(v[1]),
        text: decode(v[2]),
      }));
      chapters[Number(c[1]) - 1] = { chapter: Number(c[1]), verses };
    }
    books[Number(b[1]) - 1] = { chapters };
  }
  return { books };
}

const displayName = (n) =>
  n
    .replace(/^III /, "3 ")
    .replace(/^II /, "2 ")
    .replace(/^I /, "1 ")
    .replace(/^Revelation of John$/, "Revelation");
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

const sources = { KJV: loadJson("KJV"), BSB: loadJson("BSB"), LSG: loadXml("LSG") };
const base = sources.KJV;
const books = [];
const text = Object.fromEntries(TRANSLATIONS.map((t) => [t, []]));
const gaps = Object.fromEntries(TRANSLATIONS.map((t) => [t, 0]));

if (sources.LSG.books.length !== 66) throw new Error("LSG should have 66 books");

base.books.forEach((kb, bi) => {
  if (sources.BSB.books[bi]?.name !== kb.name) throw new Error(`Book mismatch in BSB at ${bi}`);
  const chapterCounts = [];
  const perT = Object.fromEntries(TRANSLATIONS.map((t) => [t, []]));
  const nCh = Math.max(...TRANSLATIONS.map((t) => sources[t].books[bi].chapters.length));
  for (let c = 0; c < nCh; c++) {
    const lists = TRANSLATIONS.map((t) => sources[t].books[bi].chapters[c]?.verses ?? []);
    const n = Math.max(...lists.map((vs) => vs.reduce((m, v) => Math.max(m, v.verse), 0)));
    TRANSLATIONS.forEach((t, i) => {
      const arr = Array(n).fill("");
      for (const v of lists[i]) arr[v.verse - 1] = clean(v.text);
      gaps[t] += arr.filter((s) => !s).length;
      perT[t].push(arr);
    });
    chapterCounts.push(n);
  }
  books.push({ name: displayName(kb.name), fr: FRENCH_NAMES[bi], chapters: chapterCounts });
  for (const t of TRANSLATIONS) text[t].push(perT[t]);
});

fs.writeFileSync(path.join(root, "data/bible.json"), JSON.stringify({ text }));
fs.writeFileSync(
  path.join(root, "lib/bible/books.generated.ts"),
  `// Generated by scripts/build-bible.mjs. Do not edit by hand.\n` +
    `export const BOOKS: { name: string; fr: string; chapters: number[] }[] = ${JSON.stringify(books)};\n`,
);

const total = books.reduce((s, b) => s + b.chapters.reduce((a, n) => a + n, 0), 0);
console.log(`Wrote ${books.length} books, ${total} verse slots. Empty slots per translation:`, gaps);
